"use strict";

// Generate reproducible provenance artifacts without changing source licenses.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
if (process.argv.slice(2).some(argument => argument !== "--check")) {
  throw new Error("Usage: node scripts/site_provenance.js [--check]");
}
const checkOnly = process.argv.includes("--check");
const provenance = JSON.parse(fs.readFileSync(path.join(root, "_data/site_provenance.json"), "utf8"));
const source = new URL(provenance.source);
if (source.protocol !== "https:" || !provenance.authorized_hosts.includes(source.hostname)) {
  throw new Error("The canonical HTTPS source must be included in authorized_hosts.");
}
if (!/^urn:uuid:[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/.test(provenance.identifier)) {
  throw new Error("The persistent design identifier must be a UUID URN.");
}
if (!provenance.authorized_hosts.every(host => new URL("https://" + host).hostname === host)) {
  throw new Error("authorized_hosts must contain exact lowercase hostnames, without paths or ports.");
}

let stale = false;
function writeOrCheck(relativePath, expected) {
  const filename = path.join(root, relativePath);
  if (checkOnly) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, "utf8") !== expected) {
      console.error(relativePath + " is out of date. Run: node scripts/site_provenance.js");
      stale = true;
    }
  } else {
    fs.writeFileSync(filename, expected);
  }
}

// The /*! banner and non-rendering properties survive compressed Sass output.
const css = `/*! Original personal site additions: ${provenance.creator}.
 * Source: ${provenance.source}
 * Design identifier: ${provenance.identifier}
 * Upstream software and third-party licenses remain unchanged. See /site-provenance/.
 */
// Generated by scripts/site_provenance.js; edit _data/site_provenance.json.
:root {
  --ec-design-source: ${JSON.stringify(provenance.source)};
  --ec-design-identifier: ${JSON.stringify(provenance.identifier)};
}
`;
writeOrCheck("_sass/_design-provenance.scss", css);

const files = [
  "_data/site_provenance.json",
  "_includes/author-more-links.html",
  "_includes/author-profile.html",
  "_includes/beyond-work.html",
  "_includes/education.html",
  "_includes/head.html",
  "_includes/masthead.html",
  "_includes/publication-diagram.html",
  "_includes/publications.html",
  "_includes/seo.html",
  "_includes/site-provenance.html",
  "_includes/theme-init.html",
  "_includes/theme-picker.html",
  "_includes/worked-with-logo.html",
  "_includes/worked-with.html",
  "_layouts/default.html",
  "_pages/book-a-meeting.html",
  "_pages/product-design.html",
  "_pages/site-provenance.html",
  "_sass/_author-more.scss",
  "_sass/_beyond-work.scss",
  "_sass/_design-provenance.scss",
  "_sass/_education.scss",
  "_sass/_publications.scss",
  "_sass/_site-provenance.scss",
  "_sass/_theme-picker.scss",
  "_sass/_themes.scss",
  "_sass/_worked-with.scss",
  "assets/css/main.scss",
  "assets/css/theme-picker.scss",
  "assets/js/author-more.js",
  "assets/js/beyond-work.js",
  "assets/js/news-by-year.js",
  "assets/js/site-provenance.js",
  "assets/js/theme-toggle.js",
  "scripts/site_provenance.js"
].sort();

const sha256 = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const fingerprints = Object.fromEntries(files.map(file => [
  file,
  sha256(file === "_sass/_design-provenance.scss" ? css : fs.readFileSync(path.join(root, file)))
]));
const manifest = {
  version: provenance.version,
  identifier: provenance.identifier,
  creator: provenance.creator,
  source: provenance.source,
  repository: provenance.repository,
  notice: provenance.notice,
  scope: "Content fingerprints of selected site files; existing third-party licenses remain applicable.",
  algorithm: "SHA-256",
  root_sha256: sha256(JSON.stringify(fingerprints)),
  files: fingerprints
};
writeOrCheck("assets/site-provenance.json", JSON.stringify(manifest, null, 2) + "\n");
if (stale) process.exitCode = 1;
else console.log((checkOnly ? "Verified " : "Generated ") + files.length + " source fingerprints.");
